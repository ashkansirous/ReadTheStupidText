namespace DinoReader.Core;

/// <summary>Russian: « » and „ “ quotes, dash dialogue, он/она, and past-tense verbs that show the speaker's gender.</summary>
internal static class RussianRules
{
    private static readonly HashSet<string> MaleVerbs = RuleSets.Set("сказал, спросил, ответил, крикнул, прошептал, закричал, "
        + "воскликнул, пробормотал, добавил, подумал, заметил, произнёс, произнес, проговорил, сообщил, засмеялся, вздохнул, "
        + "позвал, шепнул, буркнул, пропищал, предложил, объяснил, заявил, продолжил, взмолился, возразил, удивился, пискнул, "
        + "говорил, спрашивал, отвечал, кричал, шептал");

    private static readonly HashSet<string> FemaleVerbs = RuleSets.Set("сказала, спросила, ответила, крикнула, прошептала, "
        + "закричала, воскликнула, пробормотала, добавила, подумала, заметила, произнесла, проговорила, сообщила, засмеялась, "
        + "вздохнула, позвала, шепнула, буркнула, пропищала, предложила, объяснила, заявила, продолжила, взмолилась, "
        + "возразила, удивилась, пискнула, говорила, спрашивала, отвечала, кричала, шептала");

    private static readonly HashSet<string> OtherVerbs = RuleSets.Set("сказали, спросили, ответили, воскликнули, говорит, "
        + "говорят, спрашивает, отвечает, крикнули");

    public static LanguageRules Create() => new(
        StraightQuote: '"',
        CurlyOpenQuote: '«',
        CurlyCloseQuote: '»',
        SpeechVerbs: RuleSets.Union(RuleSets.Union(MaleVerbs, FemaleVerbs), OtherVerbs),
        AdverbSuffix: "о",
        MaleTitles: RuleSets.Set("господин, дядя, дедушка, дед, папа, отец, брат, король, принц, царь, мистер, дядюшка"),
        FemaleTitles: RuleSets.Set("госпожа, тётя, тетя, бабушка, мама, мать, сестра, королева, принцесса, царица, миссис, тётушка"),
        TitleAbbreviations: new HashSet<string>(),
        MaleNames: RuleSets.Set("пётр, петя, иван, ваня, алексей, алёша, николай, коля, сергей, андрей, дмитрий, дима, михаил, "
            + "миша, владимир, вова, александр, саша, павел, паша, олег, максим, егор, артём, антон, борис, виктор, василий, "
            + "вася, тимур, кирилл, илья, никита, данила, денис, фёдор, федя, григорий, гриша, матвей, лев, лёва, юрий, юра, "
            + "роман, степан, стёпа, костя, толя, гена, лёша, колобок, буратино, чебурашка"),
        FemaleNames: RuleSets.Set("мария, маша, анна, аня, елена, лена, ольга, оля, наталья, наташа, татьяна, таня, ирина, ира, "
            + "екатерина, катя, светлана, света, юлия, юля, анастасия, настя, софия, соня, вера, надежда, надя, любовь, люба, "
            + "галина, галя, дарья, даша, полина, алиса, василиса, ксения, ксюша, злата, кира, лиза, лара, нина, зоя, тамара, "
            + "алёна, милана, варя, варвара, людмила, мила, лиля, марина, вероника, ева, ульяна, оксана, жанна"),
        MaleSubjectPronouns: RuleSets.Set("он"),
        FemaleSubjectPronouns: RuleSets.Set("она"),
        MalePronouns: RuleSets.Set("он, его, ему"),
        FemalePronouns: RuleSets.Set("она, её, ее, ей"),
        NonNameWords: RuleSets.Set("и, а, но, или, да, же, вот, вдруг, потом, тогда, однажды, когда, как, после, перед, пока, "
            + "затем, наконец, сразу, вскоре, ну, нет, о, ах, ох, я, ты, он, она, оно, мы, вы, они, это, этот, эта, эти, тот, "
            + "там, здесь, тут, что, где, почему, зачем, кто, какой, в, на, с, у, к, по, из, за, от, до, для, при, про, без, "
            + "над, под, об, мой, моя, моё, мои, твой, твоя, твоё, наш, ваш, его, её, их, один, все, всё, каждый, привет, "
            + "здравствуй, спасибо, если, чтобы, так, тоже, ещё, уже"),
        IndefinitePronouns: RuleSets.Set("все, всё, никто, кто-то, кто-нибудь, ничего, оба, они, мы, каждый, никого"),
        SentenceTerminators: ".!?…",
        DialogueGapChars: RuleSets.GapChars,
        ExtraOpenQuotes: "„“",
        ExtraCloseQuotes: "“”",
        DialogueDashes: "—―–",
        MaleVerbs: MaleVerbs,
        FemaleVerbs: FemaleVerbs,
        MaleNameEndings: RuleSets.List("б, в, г, д, ж, з, к, л, м, н, п, р, с, т, ф, х, ц, ч, ш, щ, й"),
        FemaleNameEndings: RuleSets.List("а, я"));
}
